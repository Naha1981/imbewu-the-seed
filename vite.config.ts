import { apiApp } from './server/api.ts';

function apiPlugin(): Plugin {
  return {
    name: 'imbewu-api-plugin',
    configureServer(server) {
      server.middlewares.use('/api', (req, res, next) => {
        (apiApp as any)(req, res, next);
      });
    }
  };
}

